// ─────────────────────────────────────────────────────────────────────────────
// engine-write-guard.mjs — an agent no longer diverges a brain from its engine
// without the owner being asked (plan S3).
//
// WHAT IT CAN SEE, and the promise has to stop there: this is the decision half
// of a PreToolUse(Write|Edit) hook, so it judges TOOL CALLS. The owner editing
// `scripts/auto-commit.mjs` in their editor is invisible to it, and so are the
// engine's own writes (`update-engine`, `reconcileBrain` and the merge all write
// through `fs`, never through a tool) — which is why this guard needs no
// self-exemption, the carve-out that would otherwise be the first thing to get
// wrong.
//
// FAIL-OPEN by construction, exactly like `vault-write-guard.mjs`: it sits in
// front of every write the brain makes, so anything it cannot judge passes.
// ─────────────────────────────────────────────────────────────────────────────
import { isAbsolute, relative, sep } from "node:path";
import { globToRegExp } from "./glob-match.mjs";

/**
 * The two engine-owned files the owner is INVITED to write. Both are in the
 * `merge` regime, and that is precisely why the regimes alone cannot produce
 * this guard's verdict: "engine-owned ⇒ ask" would interrupt the owner on the
 * two files the guard exists to redirect them TO.
 *
 * Same pair as the `merge`-governed half of the sacred scrub (S2c), read from
 * the other side: S2c asks "may the ENGINE write this?", here we ask "may the
 * AGENT write this without asking?". One boundary, one constant.
 */
export const OWNER_AUTHORED = ["CLAUDE.md", ".claude/settings.json"];

/**
 * The engine's record of the version each merge-governed file came from. Never
 * a file to edit — see `guardDecision`'s deny branch for why, and note that the
 * check is anchored on this prefix rather than on the manifest.
 */
const BASE_TREE = ".engine-base/";

/**
 * The order regimes are consulted in, and it is NOT the manifest's key order.
 * A path can be claimed twice (`scripts/lib/**` under `replace` while a single
 * file inside it is named under `merge`), and the owner must be told the WORST
 * that can happen to their edit, not whichever glob was declared first.
 */
const REGIME_ORDER = ["local", "replace", "regenerate", "merge"];

/**
 * This tool call's path, relative to the brain and in posix form, or `null` when
 * it is none of the guard's business (no path, or a path outside the brain).
 *
 * `relative()` rather than a string prefix: a sibling directory whose name
 * merely STARTS with the brain's (`my-brain-backup`) is not inside it, and a
 * prefix test would have the guard ruling on another folder's files.
 */
export function brainRelative({ filePath, brainDir }) {
  if (typeof filePath !== "string") return null;
  const rel = relative(brainDir, filePath);
  if (rel === "" || rel.startsWith("..") || isAbsolute(rel)) return null;
  return rel.split(sep).join("/");
}

/** The regime that governs this brain-relative path, or `null` when none does. */
export function regimeOf({ rel, manifest }) {
  const regimes = manifest?.regimes ?? {};
  for (const regime of REGIME_ORDER) {
    const matchers = (regimes[regime] ?? []).map(globToRegExp);
    if (matchers.some((re) => re.test(rel))) return regime;
  }
  return null;
}

// The sentences the owner reads. Each names the file, the PRICE of editing it —
// which is what differs between regimes and is the whole point of the slice —
// and the layer built for what they were probably trying to do. A guard that
// only says "no" teaches nothing and gets clicked through.
const REASON = {
  merge: (rel) =>
    `${rel} is an engine file, and this brain merges it: your edit is kept, and every future ` +
    `update three-way-merges it with the new version — a clash is reported to you, never written. ` +
    `If what you want is to change how your brain behaves, CLAUDE.md is the layer built for that, ` +
    `and a skill of your own costs nothing to carry.`,
  replace: (rel) =>
    `${rel} is an engine file this brain does not merge: the next engine update will overwrite it ` +
    `with the new version, without a word, and your change will be gone. If you mean to change how ` +
    `your brain behaves, write it in CLAUDE.md, or in a skill of your own — those are yours, and no ` +
    `update touches them.`,
  regenerate: (rel) =>
    `${rel} is regenerated by the engine from a template: the next update writes it again from ` +
    `scratch and your change will be gone. If you mean to change how your brain behaves, CLAUDE.md ` +
    `is the layer built for that — a launcher is machinery, not doctrine.`,
};

/**
 * The hook's verdict on one tool call: `{ decision: "allow" }`, or
 * `{ decision: "ask" | "deny", reason }`.
 *
 * Only those three values are ever emitted. The client's dispatcher THROWS on
 * anything outside `allow | deny | ask | defer` (read out of its own binary,
 * plan S3-0), so the set is a contract rather than a style choice — and `defer`
 * is print-mode only, so it is not ours.
 */
export function guardDecision({ toolName, filePath, brainDir, manifest }) {
  if (toolName !== "Write" && toolName !== "Edit") return { decision: "allow" };

  const rel = brainRelative({ filePath, brainDir });
  if (rel === null) return { decision: "allow" };

  // THE ONE VERDICT THAT IS NOT FAIL-OPEN, and it is anchored on the path rather
  // than on the manifest: the verdict protecting a correctness invariant must not
  // be disarmed by the very file whose integrity it protects.
  //
  // Editing the recorded base does not diverge the brain — it FORGES the
  // provenance, turning a real divergence into a fast-forward that destroys the
  // owner's edit at the next update, with the record itself as the evidence that
  // nothing was wrong. There is no version of this write that can be meant, which
  // is the same bar `vault-write-guard` sets for its own deny.
  if (rel.startsWith(BASE_TREE)) {
    return {
      decision: "deny",
      reason:
        `${rel} is the engine's record of the version your files came from — the engine maintains ` +
        `it, and nothing else should write here. Changing it does not change your brain: it makes ` +
        `the next update believe you never edited the real file, so your own edit is silently ` +
        `replaced by the engine's version, with this record as the evidence that nothing was wrong.`,
    };
  }

  if (OWNER_AUTHORED.includes(rel)) return { decision: "allow" };

  // `local` lands here too, and allowing it is correct: a `local` file is the
  // brain's own, never delivered by the engine. The one such tree today is the
  // base, and it never reaches this line.
  const reason = REASON[regimeOf({ rel, manifest })];
  return reason === undefined ? { decision: "allow" } : { decision: "ask", reason: reason(rel) };
}
