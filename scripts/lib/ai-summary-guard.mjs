// ─────────────────────────────────────────────────────────────────────────────
// ai-summary-guard.mjs — the pure decision behind the PostToolUse notice: an AI
// synthesis has just been read, so say so before it becomes the source.
//
// The rule this enforces ALREADY existed in both constitutions ("verbatim >
// human synthesis > AI synthesis") and did not fire, because it is a rule about
// how to RANK sources when citing, and the choice was never presented: the
// summary arrived unasked, at the top of the very file that held the verbatim,
// in the exact shape of the asked-for deliverable. So this speaks at the moment
// the reading happens, when there is still something to do about it.
//
// Never blocks, never refuses: it returns a line of text or nothing at all.
// ─────────────────────────────────────────────────────────────────────────────

// The signatures of an automatic note-taker's synthesis. Deliberately narrow
// (§5quater): a bare product name is not a signature — "Otter" is a word, and a
// notice that fires on it is a notice its reader learns to skip.
const NOTE_TAKERS = "Gemini|Noota|Fathom|tl;dv|Otter|Fireflies|Read\\.ai";
const SUMMARY_SIGNS = [
  new RegExp(`\\bnotes?\\s+(?:par|by|de|from)\\s+(?:${NOTE_TAKERS})\\b`, "i"),
  // "Résumé de la réunion par Noota", "Summary generated by Fireflies" — the
  // taker has to appear within the same clause as the word "summary", so a
  // document that merely MENTIONS one of these products stays silent.
  new RegExp(
    // No `\b` after the accented alternatives: JS word boundaries are ASCII, so
    // `résumé\b` never matches before a space. Silent, and it cost a red run.
    `(?:résumé|resumé|summary|compte[- ]rendu)[^\\n]{0,60}\\b(?:par|by|de|from)\\s+(?:${NOTE_TAKERS})\\b`,
    "i",
  ),
  // "Gemini's notes" — the same claim with the words the other way round, which
  // is why no pattern above sees it. There WAS a third Gemini line here,
  // `/\bnotes\s+de\s+Gemini\b/`, and the mutation pass is what exposed it: every
  // one of its mutants survived, because the first signature already matches
  // every string it could ("de" is one of its connectors). A second spelling of
  // a rule is a second opinion on it, so it is gone rather than tested.
  /\bGemini['’]s\s+notes\b/i,
];

// The verbatim's own heading, when the same payload carries one.
const VERBATIM_HEADINGS = [/^\s*(Transcription)\s*$/im, /^\s*#*\s*(Transcript)\s*$/im];

// A verbatim that never labels itself: speaker turns. The two shapes the field
// exports actually use — Noota's "<name>  mm:ss" and Markdown's "**Name:**".
// Three of them, so one stray line cannot pass for a transcript.
const TURN_SHAPES = [
  /^[\p{Lu}][\p{L}'’. -]{0,30}\s{2,}\d{1,2}:\d{2}(?::\d{2})?\s*$/gmu,
  /^\*\*[^*\n]{1,40}\*\*\s*:/gm,
];
const MIN_TURNS = 3;

function hasSpeakerTurns(text) {
  return TURN_SHAPES.some((re) => (text.match(re) ?? []).length >= MIN_TURNS);
}

// How much of a payload is worth judging. A meeting export runs to 110k
// characters and the signatures all live near its top; the cap keeps a hook that
// runs on every read from walking a whole vault dump.
const MAX_TEXT = 400_000;

/**
 * Every string a tool response holds, joined by newlines — so the line-anchored
 * detections above see real lines. Shape-agnostic on purpose: which key carries
 * the text is the tool's business, and a new connector must not need a new case
 * here to be covered.
 */
export function payloadText(response) {
  const out = [];
  let size = 0;
  const walk = (value) => {
    if (size >= MAX_TEXT) return;
    if (typeof value === "string") {
      out.push(value);
      size += value.length;
      return;
    }
    if (Array.isArray(value)) {
      for (const item of value) walk(item);
      return;
    }
    if (value && typeof value === "object") {
      for (const item of Object.values(value)) walk(item);
    }
  };
  walk(response);
  return out.join("\n");
}

/**
 * The notice to hand back to the model, or `null` when there is nothing to say.
 * Pure: it is given the text, it never reads anything itself.
 */
export function summaryNotice({ text, fromSearch = false }) {
  if (!SUMMARY_SIGNS.some((re) => re.test(text))) return null;
  // A search hit is not a document that was read: it is an extract the tool
  // chose, and here it is an extract OF a synthesis. Two removes from the source,
  // and the only one of the three states where the next gesture is "open it".
  if (fromSearch) {
    return (
      `⚠️ That search hit quotes an AI synthesis. A search-result snippet is never a source — ` +
      `open the document, read the verbatim in it, and declare the tier you actually read. ` +
      `Do not lift the summary's own list of actions out of the snippet.`
    );
  }
  const heading = VERBATIM_HEADINGS.map((re) => text.match(re)?.[1]).find(Boolean);
  const where = heading
    ? `it starts at the "${heading}" section`
    : hasSpeakerTurns(text)
      ? `it is the speaker turns further down this same document`
      : null;
  if (where) {
    return (
      `⚠️ What you just read carries an AI synthesis AND the verbatim, in the same document. ` +
      `The verbatim is the source: ${where}. Read it before you write anything from this, ` +
      `and do not take the actions from the summary's own list.`
    );
  }
  // No verbatim in THIS payload is not the same as no verbatim at all — the
  // field failure read the first 140 lines of a 110k-character file, and those
  // lines were the summary. So: look further, then say what you ended up with.
  return (
    `⚠️ What you just read is an AI synthesis — the lowest source tier. Look for the verbatim ` +
    `before you write anything from this: in these exports it usually sits BELOW the summary, ` +
    `so a partial read lands on the summary alone. If there is none, say so in the note and ` +
    `declare the tier you actually read.`
  );
}
